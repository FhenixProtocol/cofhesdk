import { execSync } from 'child_process';
import * as fs from 'fs';
import { createRequire } from 'module';
import {
  COFHE_ADDRESS_BOOK_ADDRESS,
  TASK_MANAGER_ID,
  MOCKS_TASK_MANAGER_ADDRESS,
  MOCKS_ZK_VERIFIER_ADDRESS,
  MOCKS_THRESHOLD_NETWORK_ADDRESS,
} from '@cofhe/sdk';

// The SDK resolves the Task Manager through the same book + id FHE.sol is compiled against.
// Fail the build if the two drift apart.
function assertSdkMatchesFheSol(): void {
  const fheSolPath = createRequire(__filename).resolve('@fhenixprotocol/cofhe-contracts/FHE.sol');
  const source = fs.readFileSync(fheSolPath, 'utf8');
  const book = source.match(/address constant COFHE_ADDRESS_BOOK = (0x[0-9a-fA-F]{40});/)?.[1];
  const id = source.match(/uint256 constant TASK_MANAGER_ID = (\d+);/)?.[1];

  if (
    book?.toLowerCase() !== COFHE_ADDRESS_BOOK_ADDRESS.toLowerCase() ||
    id == null ||
    BigInt(id) !== TASK_MANAGER_ID
  ) {
    throw new Error(
      `@cofhe/sdk consts (COFHE_ADDRESS_BOOK_ADDRESS=${COFHE_ADDRESS_BOOK_ADDRESS}, TASK_MANAGER_ID=${TASK_MANAGER_ID}) ` +
        `do not match ${fheSolPath} (COFHE_ADDRESS_BOOK=${book}, TASK_MANAGER_ID=${id})`
    );
  }
}

assertSdkMatchesFheSol();

const contracts: Array<{ name: string; fixedAddress?: string }> = [
  {
    name: 'MockCoFHEAddressBook',
    fixedAddress: COFHE_ADDRESS_BOOK_ADDRESS,
  },
  {
    name: 'MockTaskManager',
    fixedAddress: MOCKS_TASK_MANAGER_ADDRESS,
  },
  {
    name: 'MockZkVerifier',
    fixedAddress: MOCKS_ZK_VERIFIER_ADDRESS,
  },
  {
    name: 'MockThresholdNetwork',
    fixedAddress: MOCKS_THRESHOLD_NETWORK_ADDRESS,
  },
  {
    name: 'MockACL',
  },
  {
    name: 'ACPTimestampRevoker',
  },
  {
    name: 'ACPShareRegistry',
  },
];

function inspect(contract: string, field: string): any {
  const cmd = `forge inspect ${contract} ${field} --json`;
  const out = execSync(cmd, { encoding: 'utf8' }).trim();
  return JSON.parse(out);
}

const abiDir = 'abi';
fs.rmSync(abiDir, { recursive: true, force: true });
fs.mkdirSync(abiDir, { recursive: true });

function writeArtifactFile(name: string, artifact: Record<string, unknown>, abi: any): void {
  fs.writeFileSync(
    `src/${name}.ts`,
    `// This file is auto-generated by build-artifacts.ts
import { type MockArtifact } from './types';

export const ${name}Artifact = ${JSON.stringify(artifact, null, 2)} as const satisfies MockArtifact;`
  );

  fs.writeFileSync(`${abiDir}/${name}.json`, JSON.stringify(abi, null, 2));
}

function writeFixedAddressArtifact(name: string, fixedAddress: string, abi: any): void {
  const artifact = {
    contractName: name,
    isFixed: true,
    fixedAddress,
    abi,
  };

  writeArtifactFile(name, artifact, abi);
}

function writeVariableAddressArtifact(name: string, abi: any): void {
  const artifact = {
    contractName: name,
    isFixed: false,
    abi,
  };

  writeArtifactFile(name, artifact, abi);
}

for (const { name, fixedAddress } of contracts) {
  const abi = inspect(name, 'abi');

  if (fixedAddress) {
    writeFixedAddressArtifact(name, fixedAddress, abi);
  } else {
    writeVariableAddressArtifact(name, abi);
  }
}
